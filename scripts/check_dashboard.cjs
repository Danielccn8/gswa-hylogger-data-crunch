/* Browser acceptance against a running local API; no mock network responses. */
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async()=>{
  const output=path.resolve(process.env.REVIEW_OUTPUT || 'data/delivery-20261003/browser');
  fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL || 'msedge'});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base=process.env.REVIEW_URL || 'http://127.0.0.1:8000';
  const started=Date.now();await page.goto(base);await page.locator('#hole-table tr').first().waitFor();
  const loadMs=Date.now()-started;
  const swir=await (await page.request.get(base+'/api/system/dashboard?region=swir')).json();
  assert.equal(await page.locator('#hole-table tr').count(),swir.holes.length);
  await page.screenshot({path:path.join(output,'overview.png'),fullPage:true});
  await page.getByRole('checkbox',{name:'Compare LD82625W1',exact:true}).check();
  await page.getByRole('checkbox',{name:'Compare WKDD15001',exact:true}).check();
  await page.getByRole('tab',{name:/Compare/}).click();
  assert.equal(await page.locator('#compare-content .panel').count(),2);
  await page.screenshot({path:path.join(output,'compare.png'),fullPage:true});
  await page.locator('#compare-content [data-hole="WKDD15001"]').click();
  await page.locator('#profile .interval-row').first().waitFor();
  await page.locator('#profile .interval-row').first().click();
  await page.locator('#similar-method').waitFor();
  await page.waitForFunction(()=>document.getElementById('spectrum')?.textContent.length>0);
  assert.match(await page.locator('#similar-method').textContent(),/selected interval/);
  await page.screenshot({path:path.join(output,'interval.png'),fullPage:true});
  await page.locator('#depth-from').fill('100');await page.locator('#depth-to').fill('105');
  await page.getByRole('button',{name:'Apply depth range',exact:true}).click();
  await page.waitForFunction(()=>document.getElementById('export').getAttribute('href')?.includes('from_m=100'));
  const csv=await (await page.request.get(base+await page.locator('#export').getAttribute('href'))).text();
  assert.match(csv,/interval_set_id/);assert.match(csv,/WKDD15001/);
  assert.equal(csv.trim().split('\n').length-1,await page.locator('#profile .interval-row').count());
  await page.locator('#close-detail').click();
  await page.getByRole('tab',{name:'Map',exact:true}).click();
  await page.locator('.leaflet-container').waitFor();
  assert.equal(await page.locator('.leaflet-interactive').count(),swir.holes.filter(h=>h.lat!=null&&h.lon!=null).length);
  await page.screenshot({path:path.join(output,'map.png'),fullPage:true});
  await page.getByRole('tab',{name:'Data & method',exact:true}).click();
  assert.match(await page.locator('#method-content').textContent(),/Held out/);
  await page.getByRole('tab',{name:'Overview',exact:true}).click();
  await page.locator('#search').fill('NO_SUCH_HOLE');assert.equal(await page.locator('#hole-table tr').count(),0);
  assert.equal(await page.locator('#table-empty').isVisible(),true);
  await page.getByRole('button',{name:'Reset filters',exact:true}).click();
  await page.locator('#sensor').selectOption('tir');await page.locator('#hole-table tr').first().waitFor();
  const tir=await (await page.request.get(base+'/api/system/dashboard?region=tir')).json();
  assert.equal(await page.locator('#hole-table tr').count(),tir.holes.length);
  await page.setViewportSize({width:390,height:1000});await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.route('https://**/*',route=>route.abort());
  await page.reload();await page.locator('#hole-table tr').first().waitFor();
  await page.getByRole('tab',{name:'Map',exact:true}).click();await page.locator('.leaflet-container').waitFor();
  assert.ok(await page.locator('.leaflet-interactive').count()>0);
  assert.deepEqual(errors,[]);
  const report={loadMs,swirHoles:swir.holes.length,tirHoles:tir.holes.length,
    checks:['overview','compare','interval and similarity','filtered CSV','map markers','method','empty state','sensor change','mobile overflow','offline basemap fallback'],pageErrors:errors};
  fs.writeFileSync(path.join(output,'acceptance.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
